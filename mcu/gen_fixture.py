"""Build the E5 fixture from real data and frozen hyperparameters, compile the
host reference of the C suite, and write the expected outputs.

Usage: python mcu/gen_fixture.py   (needs data/extracted and data/cache)

Writes mcu/include/enose_fixture.h, mcu/include/enose_expected.h and
mcu/fixture_manifest.json. The manifest records host-C versus Python parity:
predictions of the C float32 kernels against the float64 Python methods, and
bit-exactness of the streaming extractor against the numpy float32 one.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "src"))

from enose_drift import methods as M  # noqa: E402
from enose_drift import transfer as T  # noqa: E402
from enose_drift.data import D2_GASES, list_d2, load_d1  # noqa: E402
from enose_drift.features import BASELINE_SECONDS, StreamingExtractor  # noqa: E402
from enose_drift.stream import feature_index, make_source  # noqa: E402

SEED = 20270131 + 500
N16, N128, OLS_K, DS_K, DS_N, EXT_N, EXT_STRIDE = 64, 32, 20, 16, 64, 512, 20
CFLAGS = ["-std=c11", "-O2", "-fno-fast-math", "-ffp-contract=off", "-Wall", "-Wextra"]


def flit(v):
    if not np.isfinite(v):
        return "INFINITY" if v > 0 else "-INFINITY"
    t = f"{float(v):.9g}"
    return (t if any(ch in t for ch in ".e") else t + ".0") + "f"


def farr(name, a, flash=True, guard=None):
    a = np.asarray(a, np.float32).ravel()
    body = ",".join(flit(v) for v in a)
    s = f"static const float {name}[{a.size}] {'EK_FLASH ' if flash else ''}= {{{body}}};\n"
    return f"#if {guard}\n{s}#endif\n" if guard else s


def uarr(name, a):
    a = np.asarray(a, np.uint8).ravel()
    return f"static const uint8_t {name}[{a.size}] EK_FLASH = {{{','.join(str(int(v)) for v in a)}}};\n"


def main():
    hp12 = json.loads((ROOT / "results/e1e2_20261109/hyperparameters.json").read_text())
    hp4 = json.loads((ROOT / "results/e4_20261109/hyperparameters.json").read_text())
    d1 = load_d1(ROOT / "data/extracted/D1b")
    rng = np.random.default_rng(SEED)
    idx7 = np.flatnonzero(d1.batch == 7)
    idx7 = idx7[rng.permutation(len(idx7))]
    out, py = [], {}
    out.append("/* Generated by mcu/gen_fixture.py; do not edit. */\n#pragma once\n#include <stdint.h>\n#include <math.h>\n")
    out.append("#ifndef EK_FLASH\n#define EK_FLASH\n#endif\n")
    out.append(f"#define FX_N16 {N16}\n#define FX_N128 {N128}\n#define FX_OLS_K {OLS_K}\n#define FX_DS_K {DS_K}\n#define FX_DS_N {DS_N}\n#define FX_EXT_N {EXT_N}\n")
    for d, n in ((16, N16), (128, N128)):
        h = hp12[str(d)]
        fi = feature_index(d)
        b1 = d1.batch == 1
        src = make_source(d1.X[b1][:, fi], d1.gas[b1], h["head_lambda"])
        X = d1.X[idx7[:n]][:, fi].astype(np.float32)
        y = d1.gas[idx7[:n]]
        mh = h["methods"]
        out += [farr(f"FX_D1_X{d}", X), uarr(f"FX_D1_Y{d}", y), farr(f"FX_D1_W{d}", src.W),
                farr(f"FX_D1_MU{d}", src.pre.mu), farr(f"FX_D1_SD{d}", src.pre.sd)]
        out.append(f"#define FX_M1_ALPHA{d} {mh['M1']['alpha']}f\n#define FX_M5_MU{d} {mh['M5']['mu']}f\n#define FX_M6_FORGET{d} {mh['M6']['forget']}f\n")
        out.append(farr(f"FX_P0_{d}", src.P0, guard="EK_HAVE_RLS128" if d == 128 else None))
        if d == 16:
            out.append(f"#define FX_M7_GAMMA16 {mh['M7']['gamma']}f\n")
        # Python float64 references on the float32-rounded inputs.
        Z = src.pre(X.astype(np.float64))
        py[f"static{d}"] = M.Static(src.W, 6).predict_many(Z).tolist()
        m1 = M.EWMAStandardise(src.W, 6, d, mh["M1"]["alpha"]); py[f"m1_{d}"] = [int(m1.observe(z)) for z in Z]
        for name, meth in ((f"nlms{d}", M.NLMS(src.W, 6, mh["M5"]["mu"])),
                           (f"rls{d}", M.RLS(src.W, 6, mh["M6"]["forget"], None, P0=src.P0))):
            preds = []
            for z, t in zip(Z, y):
                preds.append(int(meth.predict_many(z[None])[0])); meth.reference(z, int(t))
            py[name] = preds
        if d == 16:
            ols = M.BlockOLS(src.W, 6, mh["M7"]["gamma"])
            for z, t in zip(Z[:OLS_K], y[:OLS_K]):
                ols.reference(z, int(t))
            ols.end_reference_session()
            py["ols16"] = ols.predict_many(Z[OLS_K:]).tolist()
    # D2: board 1 master head, DS to board 2.
    z2 = np.load(ROOT / "data/cache/d2_features.npz")
    X2 = z2["X"].reshape(-1, 8, 8)[:, :, :2].reshape(len(z2["X"]), -1)
    gases = ("co", "ethanol", "ethylene", "methane")
    y2 = np.array([gases.index(g) for g in z2["gas"]])
    board, lev, rep, gas = z2["board"], z2["level"], z2["repetition"], z2["gas"]
    h4 = hp4["16"]
    src2 = make_source(X2[board == 1], y2[board == 1], h4["head_lambda"], classes=4)
    conds = sorted({(g, l) for g, l in zip(gas[board == 2], lev[board == 2])})
    chosen = [conds[t] for t in rng.permutation(len(conds))[:DS_K]]
    S, Mm, used = [], [], []
    for g, l in chosen:
        sj = np.flatnonzero((board == 2) & (gas == g) & (lev == l) & (rep == 1))[0]
        si = np.flatnonzero((board == 1) & (gas == g) & (lev == l) & (rep == 1))[0]
        S.append(X2[sj]); Mm.append(X2[si]); used.append(sj)
    ev = np.setdiff1d(np.flatnonzero(board == 2), used)
    ev = ev[rng.permutation(len(ev))][:DS_N]
    out += [farr("FX_D2_W", src2.W), farr("FX_D2_MU", src2.pre.mu), farr("FX_D2_SD", src2.pre.sd),
            farr("FX_DS_SLAVE", np.array(S)), farr("FX_DS_MASTER", np.array(Mm)), farr("FX_DS_EVAL", X2[ev]),
            f"#define FX_DS_RHO {h4['methods']['M8']['rho']}f\n"]
    ds = T.DirectStandardisation(src2.W, 4, h4["methods"]["M8"]["rho"])
    for s_, m_ in zip(src2.pre(np.array(S, np.float32).astype(float)), src2.pre(np.array(Mm, np.float32).astype(float))):
        ds.pair(s_, m_)
    ds.fit()
    py["ds16_apply"] = ds.predict_many(src2.pre(X2[ev].astype(np.float32).astype(float))).tolist()
    # Extractor: one raw trace of board 1, every EXT_STRIDE-th sample.
    rec = list_d2(ROOT / "data/extracted/D2")[0]
    tr = rec.load()[::EXT_STRIDE][:EXT_N].astype(np.float32)
    out += [farr("FX_EXT_T", tr[:, 0]), farr("FX_EXT_R", tr[:, 1:]), f"#define FX_EXT_TBASE {BASELINE_SECONDS}f\n"]
    ex = StreamingExtractor(8)
    for row in tr:
        ex.push(np.float32(row[0]), row[1:])
    py_features = ex.features()
    fixture = "".join(out)
    (HERE / "include/enose_fixture.h").write_text(fixture)

    with tempfile.TemporaryDirectory() as tmp:
        exe = Path(tmp) / "host_bench"
        subprocess.run(["gcc", *CFLAGS, "-I", str(HERE / "include"), str(HERE / "host/host_bench.c"), "-lm", "-o", str(exe)], check=True)
        lines = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout.splitlines()
    host = {r["routine"]: r for r in map(json.loads, lines)}

    exp = ["/* Generated by mcu/gen_fixture.py from the host reference build; do not edit. */\n#pragma once\n#include <stdint.h>\n#include <math.h>\n#ifndef EK_FLASH\n#define EK_FLASH\n#endif\n"]
    order = ["static16", "static128", "m1_16", "m1_128", "nlms16", "nlms128", "rls16", "rls128", "ols16", "ds16_fit", "ds16_apply"]
    for name in order:
        r = host[name]
        exp.append(f"static const uint8_t EXP_{name.upper()}[{max(1, len(r['pred']))}] EK_FLASH = {{{','.join(map(str, r['pred'])) or '0'}}};\n")
        exp.append(f"#define EXP_{name.upper()}_AUX {flit(r['aux'])}\n")
    exp.append(farr("EXP_FEATURES", host["extract"]["features"]))
    (HERE / "include/enose_expected.h").write_text("".join(exp))

    parity = {}
    for name, ref in py.items():
        c = host[name]["pred"]
        parity[name] = dict(n=len(ref), agree=int(sum(int(a) == int(b) for a, b in zip(c, ref))))
    cf = np.array(host["extract"]["features"], np.float32)
    parity["extract_bit_exact"] = bool(np.array_equal(cf, py_features))
    parity["extract_max_abs_diff"] = float(np.max(np.abs(cf - py_features)))
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    manifest = dict(seed=SEED, sizes=dict(N16=N16, N128=N128, OLS_K=OLS_K, DS_K=DS_K, DS_N=DS_N, EXT_N=EXT_N, EXT_STRIDE=EXT_STRIDE),
                    sources=dict(d1="D1b batch 7 (seeded permutation)", d2_transfer="board 1 -> board 2, d=16",
                                 extractor=rec.path.name),
                    hyperparameters=dict(e1e2=hp12, e4=hp4["16"]), host_cflags=CFLAGS, parity_host_c_vs_python=parity,
                    sha256={p.name: sha(p) for p in (HERE / "include/enose_fixture.h", HERE / "include/enose_expected.h",
                                                     HERE / "include/enose_kernels.h", HERE / "include/enose_suite.h")})
    (HERE / "fixture_manifest.json").write_text(json.dumps(manifest, indent=1))
    print(json.dumps(parity, indent=1))


if __name__ == "__main__":
    main()
